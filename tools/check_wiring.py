#!/usr/bin/env python3
"""Wiring check: every command a packaged desktop entry, autostart, keybind,
taskbar module or hook calls must actually exist in the image.

This exists because the v6 pack import mangled paths and left `smth-clock`,
`smth-open`, `smth-glance`, `smth-mode`, `smth-moded`, `smth-vm`,
`smth-term-overlay`, `smth-corelink` and `smth-kbd` outside `usr/local/bin`
while the shell still referenced them. Nothing failed at build time; the
desktop simply had dead buttons, dead taskbar modules and a file manager that
could not open files.

Usage: python3 tools/check_wiring.py [-v]
Exit status 1 on any unresolved command or icon.
"""
import json
import pathlib
import re
import shlex
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
INC = ROOT / "config/includes.chroot_after_packages"
VERBOSE = "-v" in sys.argv

# Binaries provided by the Rust workspace (built by scripts/build.sh).
RUST_BINS = {"smthd", "smth-ahian", "smthctl-core"}
# Binaries compiled from native/ by scripts/build.sh and installed into
# /usr/local/bin. They are not source files in the image tree, so the resolver
# has to know them by name (same approach as RUST_BINS).
NATIVE_BINS = {"smth-glance", "smth-moded"}
# Distribution binaries from config/package-lists/*.list.chroot.
SYSTEM_BINS = {
    "alacritty", "bash", "bluetoothctl", "curl", "dconf",     "file", "flock", "free", "fuzzel",
    "gtk-update-icon-cache", "hostnamectl", "kdeconnect-cli", "labwc", "nmcli",
    "notify-send", "nft", "pkill", "powerprofilesctl", "python3", "qemu-img",
    "qemu-system-aarch64", "qemu-system-x86_64", "sed", "setsid", "sh", "slurp",
    "swaybg", "swayidle", "swaylock", "systemctl", "udisksctl", "udevadm",
    "update-desktop-database", "update-mime-database", "waybar", "wayvnc", "wine",
    "wl-copy", "wl-paste", "wlr-randr", "wpctl", "wvkbd-mobintl", "pw-play",
    "box64", "waydroid", "flatpak", "openssl", "mount", "mountpoint", "umount",
    "zx", "zsh", "fastfetch", "grim", "file-roller", "python3.12",
}

# waybar/taskbar verbs are handled by waybar itself, not spawned.
WAYBAR_ACTIONS = {
    "activate", "close", "minimize", "maximize", "restore", "raise", "lower",
    "toggle", "next", "prev", "none", "activate-or-minimize",
}

failures = []


def fail(where, message):
    failures.append(f"{where}: {message}")


def resolve(token):
    """Return True when `token` resolves inside the image or is a known binary."""
    token = token.strip().strip('"\'')
    if not token:
        return True
    if token in RUST_BINS or token in NATIVE_BINS or token in SYSTEM_BINS:
        return True
    if token.startswith("/"):
        rel = token.lstrip("/")
        candidates = [INC / rel]
        # Absolute paths into /usr/bin may be Rust binaries or packaged binaries.
        if rel.startswith("usr/bin/") and rel.split("/", 2)[2] in RUST_BINS:
            return True
        return any(p.exists() for p in candidates)
    for sub in ("usr/local/bin", "usr/bin", "usr/local/sbin"):
        if (INC / sub / token).exists():
            return True
    return False


def command_of(value):
    value = value.strip()
    if not value:
        return None
    try:
        parts = shlex.split(value)
    except ValueError:
        return value.split()[0]
    if not parts:
        return None
    return parts[0]


# Icons are generated into the image by gen_icons.py, so resolve against the
# generated set rather than against files that do not exist in the repository.
def generated_icons():
    text = (INC / "usr/local/share/smth/icons/gen_icons.py").read_text()
    return set(re.findall(r'"(smth-[a-z]+)":', text))


def scan_desktop_entries():
    apps = INC / "usr/share/applications"
    icons = generated_icons()
    for path in sorted(apps.glob("*.desktop")):
        where = path.relative_to(ROOT)
        text = path.read_text(encoding="utf-8", errors="replace")
        execs = re.findall(r"^Exec=(.+)$", text, re.MULTILINE)
        if not execs:
            fail(where, "no Exec= line")
        for line in execs:
            cmd = command_of(line)
            if cmd and not resolve(cmd):
                fail(where, f"Exec command not in the image: {cmd!r} (from {line!r})")
            if VERBOSE:
                print(f"  ok {where.name}: {cmd}")
        icons_found = re.findall(r"^Icon=(.+)$", text, re.MULTILINE)
        for icon in icons_found:
            icon = icon.strip()
            if icon.startswith("/"):
                if not (INC / icon.lstrip("/")).exists():
                    fail(where, f"Icon path missing: {icon}")
                continue
            if icon.startswith("smth-") and icon not in icons:
                fail(where, f"icon is never generated by gen_icons.py: {icon}")


def scan_autostart():
    for name in ("etc/skel/.config/labwc/autostart",):
        path = INC / name
        if not path.exists():
            fail(name, "missing autostart file")
            continue
        for lineno, line in enumerate(path.read_text().splitlines(), 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            # Strip shell grouping/subshell fragments: `|| { ... }` blocks span
            # several lines, and the braces are syntax, not commands.
            for chunk in re.split(r"[();]|&&|\|\|", line):
                chunk = chunk.strip().strip("{}()").strip()
                if not chunk or chunk.startswith(("exec ", "timeout ", "sleep ")):
                    continue
                cmd = command_of(chunk.split(">/dev/null")[0])
                if cmd and not resolve(cmd):
                    fail(f"{name}:{lineno}", f"autostart command not in the image: {cmd!r}")


def scan_keybinds():
    for path in sorted((INC / "etc/skel/.config").rglob("rc-*.xml")) + [
        INC / "etc/skel/.config/labwc/rc.xml"
    ]:
        if not path.exists():
            continue
        where = path.relative_to(ROOT)
        for lineno, line in enumerate(path.read_text().splitlines(), 1):
            m = re.search(r'command="([^"]+)"', line)
            if not m:
                continue
            cmd = command_of(m.group(1))
            if cmd and not resolve(cmd):
                fail(f"{where}:{lineno}", f"keybind command not in the image: {cmd!r}")


def scan_waybar():
    for path in sorted((INC / "etc/skel/.config/smth").glob("waybar-*.jsonc")):
        where = path.relative_to(ROOT)
        text = path.read_text(encoding="utf-8", errors="replace")
        try:
            # jsonc is JSON here apart from comments; strip // comments.
            data = json.loads(re.sub(r"(?m)^\s*//.*$", "", text))
        except json.JSONDecodeError as e:
            fail(where, f"invalid waybar config: {e}")
            continue
        bars = data if isinstance(data, list) else [data]
        if not all(isinstance(bar, dict) for bar in bars):
            fail(where, "waybar config must be an object or a list of bars")
            continue
        for key, module in (item for bar in bars for item in bar.items()):
            if not isinstance(module, dict):
                continue
            for field in ("exec", "on-click", "on-click-right", "on-click-middle"):
                value = module.get(field)
                if not value:
                    continue
                if value in WAYBAR_ACTIONS:
                    continue
                cmd = command_of(value)
                if cmd and not resolve(cmd):
                    fail(where, f"{key}.{field} command not in the image: {cmd!r}")
            exec_if = module.get("exec-if")
            if exec_if and not resolve(command_of(exec_if)):
                fail(where, f"{key}.exec-if command not in the image: {exec_if!r}")


def scan_hook_commands():
    path = ROOT / "config/hooks/normal/0100-system.hook.chroot"
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        for m in re.finditer(r"\bpython3 (/[^\s]+)", line):
            if not (INC / m.group(1).lstrip("/")).exists():
                fail(f"{path.relative_to(ROOT)}:{lineno}", f"hook runs missing script: {m.group(1)}")
        for m in re.finditer(r"^(?:ln -sf|install|cp) (\S+)", line):
            pass


def scan_scripts():
    """Shell/Python scripts in usr/local/bin must at least parse."""
    import subprocess
    for path in sorted((INC / "usr/local/bin").iterdir()):
        if not path.is_file():
            continue
        first = path.open("rb").readline(200).decode("utf-8", "replace")
        if "python" in first:
            r = subprocess.run([sys.executable, "-m", "py_compile", str(path)],
                               capture_output=True, text=True)
            if r.returncode:
                fail(path.relative_to(ROOT), f"Python syntax error: {r.stderr.strip().splitlines()[-1]}")
        elif "bash" in first or "sh" == first.split()[0][2:]:
            r = subprocess.run(["bash", "-n", str(path)], capture_output=True, text=True)
            if r.returncode:
                fail(path.relative_to(ROOT), f"shell syntax error: {r.stderr.strip()}")
        if not path.stat().st_mode & 0o111:
            fail(path.relative_to(ROOT), "not executable (launchers and autostart need +x)")


def scan_icon_theme():
    """Every shipped app icon referenced by a .desktop must be generated."""
    gen = INC / "usr/local/share/smth/icons/gen_icons.py"
    text = gen.read_text()
    generated = set(re.findall(r'"(smth-[a-z]+)":', text))
    for path in sorted((INC / "usr/share/applications").glob("*.desktop")):
        m = re.search(r"^Icon=(.+)$", path.read_text(), re.MULTILINE)
        if m and m.group(1).startswith("smth-") and m.group(1) not in generated:
            fail(path.relative_to(ROOT), f"icon {m.group(1)} is never generated")


def main():
    scan_desktop_entries()
    scan_autostart()
    scan_keybinds()
    scan_waybar()
    scan_hook_commands()
    scan_scripts()
    scan_icon_theme()
    if failures:
        print(f"FAIL wiring: {len(failures)} problem(s)")
        for item in failures:
            print(f"  - {item}")
        return 1
    print("PASS wiring: desktop entries, autostart, keybinds, taskbar, hooks and scripts resolve")
    return 0


if __name__ == "__main__":
    sys.exit(main())
